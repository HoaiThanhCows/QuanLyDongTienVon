create table if not exists public.profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null,
 role text not null check(role in ('manager','investor_qui','investor_vu'))
);
alter table public.profiles add column if not exists must_change_password boolean not null default false;
create table if not exists public.capital_transactions (
 id bigint generated by default as identity primary key,
 transaction_date date not null,
 kind text not null check(kind in ('capital_in','expense')),
 amount numeric(14,0) not null check(amount>0),
 investor text check(investor in ('Qui','Vu')),
 category text, payee text, note text,
 created_by uuid not null references auth.users(id),
 created_by_email text,
 created_at timestamptz not null default now(),
 constraint capital_in_requires_investor check((kind='capital_in' and investor is not null) or (kind='expense' and investor is null))
);
create table if not exists public.wallet_withdrawals (
 id bigint generated by default as identity primary key,
 withdrawal_date date not null,
 site text not null check(site in ('Tan Nhut','Vinh Loc')),
 amount numeric(14,0) not null check(amount>0),
 period text not null check(period in ('Tuan','Thang','Khac')),
 handover_to text, note text,
 created_by uuid not null references auth.users(id),
 created_at timestamptz not null default now()
);
create index if not exists capital_transactions_date_idx on public.capital_transactions(transaction_date);
create index if not exists wallet_withdrawals_date_idx on public.wallet_withdrawals(withdrawal_date);
alter table public.profiles enable row level security;
alter table public.capital_transactions enable row level security;
alter table public.wallet_withdrawals enable row level security;

-- Người dùng chỉ có thể tự hoàn tất cờ bắt buộc đổi mật khẩu thông qua RPC này.
create or replace function public.complete_password_change()
returns void
language sql
security definer
set search_path=''
as $$ update public.profiles set must_change_password=false where user_id=(select auth.uid()) $$;
revoke all on function public.complete_password_change() from public;
grant execute on function public.complete_password_change() to authenticated;

create or replace function public.current_capital_role() returns text language sql stable security definer set search_path=''
as $$ select p.role from public.profiles p where p.user_id=(select auth.uid()) limit 1 $$;
revoke all on function public.current_capital_role() from public;
grant execute on function public.current_capital_role() to authenticated;
drop policy if exists "profile self read" on public.profiles;
create policy "profile self read" on public.profiles for select to authenticated using(user_id=(select auth.uid()) or public.current_capital_role()='manager');
drop policy if exists "manager profile manage" on public.profiles;
create policy "manager profile manage" on public.profiles for all to authenticated using(public.current_capital_role()='manager') with check(public.current_capital_role()='manager');
drop policy if exists "authenticated read capital ledger" on public.capital_transactions;
create policy "authenticated read capital ledger" on public.capital_transactions for select to authenticated using(public.current_capital_role() in ('manager','investor_qui','investor_vu'));
drop policy if exists "manager insert capital ledger" on public.capital_transactions;
create policy "manager insert capital ledger" on public.capital_transactions for insert to authenticated with check(public.current_capital_role()='manager' and created_by=(select auth.uid()));
drop policy if exists "manager update capital ledger" on public.capital_transactions;
create policy "manager update capital ledger" on public.capital_transactions for update to authenticated using(public.current_capital_role()='manager') with check(public.current_capital_role()='manager');
drop policy if exists "manager delete capital ledger" on public.capital_transactions;
create policy "manager delete capital ledger" on public.capital_transactions for delete to authenticated using(public.current_capital_role()='manager');
drop policy if exists "authenticated read wallet ledger" on public.wallet_withdrawals;
create policy "authenticated read wallet ledger" on public.wallet_withdrawals for select to authenticated using(public.current_capital_role() in ('manager','investor_qui','investor_vu'));
drop policy if exists "manager insert wallet ledger" on public.wallet_withdrawals;
create policy "manager insert wallet ledger" on public.wallet_withdrawals for insert to authenticated with check(public.current_capital_role()='manager' and created_by=(select auth.uid()));
drop policy if exists "manager update wallet ledger" on public.wallet_withdrawals;
create policy "manager update wallet ledger" on public.wallet_withdrawals for update to authenticated using(public.current_capital_role()='manager') with check(public.current_capital_role()='manager');
drop policy if exists "manager delete wallet ledger" on public.wallet_withdrawals;
create policy "manager delete wallet ledger" on public.wallet_withdrawals for delete to authenticated using(public.current_capital_role()='manager');

